# TaskFlow AI - one-click local setup (Windows PowerShell)
# Usage (from the project root):  powershell -ExecutionPolicy Bypass -File setup-env.ps1
# Asks for your MongoDB Atlas DB password, writes server/.env, seeds demo data and starts the app.

$ErrorActionPreference = 'Stop'
Set-Location -Path $PSScriptRoot

Write-Host "`n=== TaskFlow AI setup ===`n" -ForegroundColor Cyan

$dbUser  = 'mohithingase04_db_user'
$cluster = 'cluster0.zv4umod.mongodb.net'

$secure = Read-Host "MongoDB Atlas password for '$dbUser'" -AsSecureString
$plain  = [Runtime.InteropServices.Marshal]::PtrToStringAuto([Runtime.InteropServices.Marshal]::SecureStringToBSTR($secure))
if ([string]::IsNullOrWhiteSpace($plain)) { Write-Host 'Password empty - aborting.' -ForegroundColor Red; exit 1 }
$pass   = [uri]::EscapeDataString($plain)   # handles special characters like @ # / :

$gemini = Read-Host "Gemini API key (optional - just press Enter to skip)"
$jwt    = ([guid]::NewGuid().ToString('N') + [guid]::NewGuid().ToString('N'))

$envText = @"
# Generated by setup-env.ps1
PORT=5000
NODE_ENV=development
CLIENT_URL=http://localhost:5173
MONGO_URI=mongodb+srv://${dbUser}:${pass}@${cluster}/taskflow_ai?retryWrites=true&w=majority&appName=Cluster0
JWT_SECRET=$jwt
JWT_EXPIRES_IN=7d
GEMINI_API_KEY=$gemini
GEMINI_MODEL=gemini-2.0-flash
"@

# UTF-8 without BOM so dotenv reads it cleanly
[IO.File]::WriteAllText((Join-Path $PSScriptRoot 'server\.env'), $envText, (New-Object System.Text.UTF8Encoding $false))
Write-Host "`n[OK] server\.env created" -ForegroundColor Green

if (-not (Test-Path 'node_modules') -or -not (Test-Path 'server\node_modules') -or -not (Test-Path 'client\node_modules')) {
  Write-Host "`nInstalling packages..." -ForegroundColor Cyan
  npm run install:all
}

Write-Host "`nSeeding demo data into Atlas..." -ForegroundColor Cyan
npm run seed
if ($LASTEXITCODE -ne 0) {
  Write-Host "`n[X] Seed failed. 'bad auth' = wrong password -> run this script again." -ForegroundColor Red
  Write-Host "    'timeout' / 'querySrv' = add your IP in Atlas > Network Access." -ForegroundColor Red
  exit 1
}

Write-Host "`nStarting app -> open http://localhost:5173  (login: demo@taskflow.ai / demo1234)`n" -ForegroundColor Green
npm run dev
